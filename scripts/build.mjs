import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';
const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const portable=process.argv.includes('--portable');
const font=portable ? 'data:font/ttf;base64,'+readFileSync(resolve(root,'assets/fonts/Manrope.ttf')).toString('base64') : '/assets/fonts/Manrope.ttf';
const css=readFileSync(resolve(root,'src/styles.css'),'utf8').replace('__BODY_FONT__',()=>font);
const js=readFileSync(resolve(root,'src/app.js'),'utf8');
const html=readFileSync(resolve(root,'src/index.template.html'),'utf8').replace('/*__STYLES__*/',()=>css).replace('/*__SCRIPT__*/',()=>js);
const license=readFileSync(resolve(root,'assets/fonts/Manrope-OFL.txt'),'utf8');
const output=portable?'Freq-Design-Review.html':'index.html';
writeFileSync(resolve(root,output),html.replace('</head>',()=>`<!-- Bundled font license\n${license}\n-->\n</head>`));
console.log(`Built ${output}`);
